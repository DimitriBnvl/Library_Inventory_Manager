public class Product {
    String productId;
    String name;
    int price;
    String type;
    String code;
    int stock;

    public Product(String productId, String name, int price, String type, String code, int stock) {
        this.productId = productId;
        this.name = name;
        this.price = price;
        this.type = type;
        this.code = code;
        this.stock = stock;
    }
}
